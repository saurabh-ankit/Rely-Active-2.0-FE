export type ResourceKey = (typeof RESOURCE)[keyof typeof RESOURCE]

/** Each module's sub-modules (sections), derived from RESOURCE: e.g. EMPLOYEE → [EMPLOYEE.DIRECTORY, …]. */
export const SUB_MODULES: Record<string, string[]> = Object.values(RESOURCE).reduce<Record<string, string[]>>(
  (acc, key) => {
    const at = key.indexOf('.')
    if (at !== -1) (acc[key.slice(0, at)] ??= []).push(key)
    return acc
  },
  {},
)
